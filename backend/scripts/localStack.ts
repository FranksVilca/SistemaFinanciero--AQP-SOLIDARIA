/**
 * Starts the whole system on this machine, with no AWS account: Floci (with IAM and the Docker socket) runs the stack
 * of infra/template.yaml, the real Lambda code runs in containers, demo users sign in through the emulated Cognito,
 * and the SPA is served by Vite pointing at it.
 *
 *   npm run local            (from the repository root)
 *
 * It leaves the stack deployed and the SPA running until you press Ctrl+C. Everything lives in the emulator's memory,
 * so restarting the Floci container wipes it and this command must be run again.
 */
import { execSync, spawn } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { FLOCI_ENV } from "../test/floci/flociEnv.js";
import {
  DEMO_PASSWORD,
  DEMO_USERS,
  LOCAL_STACK_NAME,
  bootLocalStack,
  type LocalStack,
} from "../test/floci/helpers/localStack.js";

const BACKEND_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const REPOSITORY_ROOT = resolve(BACKEND_ROOT, "..");
const COMPOSE_FILE = resolve(BACKEND_ROOT, "test/floci/docker-compose.lambda.yml");
const FRONTEND_URL = "http://localhost:3000";
const HEALTH_ATTEMPTS = 60;
const HEALTH_WAIT_MS = 1_000;

async function isEmulatorUp(): Promise<boolean> {
  try {
    return (await fetch(`${FLOCI_ENV.FLOCI_ENDPOINT}/_floci/health`)).ok;
  } catch {
    return false;
  }
}

async function ensureEmulator(): Promise<void> {
  if (await isEmulatorUp()) return;
  console.log("Starting Floci (with IAM, TLS and the Docker socket) ...");
  execSync(`docker compose -f "${COMPOSE_FILE}" up -d`, { stdio: "inherit" });
  for (let attempt = 0; attempt < HEALTH_ATTEMPTS; attempt++) {
    if (await isEmulatorUp()) return;
    await new Promise((resolveWait) => setTimeout(resolveWait, HEALTH_WAIT_MS));
  }
  throw new Error("Floci did not become healthy");
}

function writeFrontendEnvironment(stack: LocalStack): string {
  const file = resolve(REPOSITORY_ROOT, "frontend/.env.local");
  writeFileSync(
    file,
    [
      "# Generated by `npm run local`. Points the SPA at the local emulator; do not commit.",
      `VITE_API_BASE_URL=${stack.baseUrl}/v1`,
      `VITE_COGNITO_AUTHORITY=${stack.authority}`,
      `VITE_COGNITO_CLIENT_ID=${stack.pool.clientId}`,
      "",
    ].join("\n")
  );
  return file;
}

/** The certificate the browser has to trust to talk to the emulator over https (its OIDC issuer is https). */
function exportEmulatorCertificate(): string | undefined {
  const target = resolve(REPOSITORY_ROOT, ".local");
  mkdirSync(target, { recursive: true });
  const file = resolve(target, "floci-root-ca.crt");
  try {
    const container = execSync(`docker ps --filter "publish=4566" --format "{{.Names}}"`)
      .toString()
      .trim()
      .split(/\s+/)[0];
    execSync(`docker cp ${container}:/app/data/tls/floci-root-ca.crt "${file}"`, { stdio: "ignore" });
    return file;
  } catch {
    return undefined;
  }
}

function printSummary(stack: LocalStack, envFile: string, certificate: string | undefined): void {
  const users = DEMO_USERS.map((user) => `   ${user.email.padEnd(28)} ${user.role}`).join("\n");
  const trust = certificate
    ? `:\n   ${certificate}\n   (Windows: certutil -user -addstore Root "${certificate}")`
    : ".";
  console.log(`
==============================================================================
 AQP-SOLIDARIA is running locally (no AWS account)

 Frontend:  ${FRONTEND_URL}
 API:       ${stack.baseUrl}/v1
 Login:     ${stack.authority}

 Demo users (password: ${DEMO_PASSWORD})
${users}

 BEFORE you sign in, the browser must trust the emulator's certificate (without it the Sign in button fails).
 Windows, once per emulator start:  npm run local:trust   (accept the Windows prompt), then restart the browser.
 Any system: open https://localhost:4566/_floci/health and accept the warning, or install the certificate${trust}

 Written: ${envFile}
 Press Ctrl+C to stop the frontend (the stack stays deployed in Floci).
==============================================================================
`);
}

async function main(): Promise<void> {
  await ensureEmulator();
  console.log("Packaging the functions and deploying infra/template.yaml ...");
  const stack = await bootLocalStack(LOCAL_STACK_NAME, "aqp-local-auth");

  printSummary(stack, writeFrontendEnvironment(stack), exportEmulatorCertificate());

  const frontend = spawn("npm", ["run", "dev", "--workspace=frontend"], {
    cwd: REPOSITORY_ROOT,
    stdio: "inherit",
    shell: true,
  });
  await new Promise<void>((resolveExit) => frontend.on("exit", () => resolveExit()));
}

main().catch((error: unknown) => {
  console.error(error);
  process.exit(1);
});
